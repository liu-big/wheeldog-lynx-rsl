#!/usr/bin/env python3
"""Pinocchio FK + scipy optimize → dog-stance q0 for Wheeldog.

Fixes H1 (small outward), solves H2/K so all wheel centers sit at z=r
when base_link is at target height. Writes YAML consumed by robot cfg.

Usage (strip ROS PYTHONPATH — it shadows pinocchio):
  unset PYTHONPATH
  python wheeldog_ext/scripts/optimize_stand_q0_pinocchio.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

# Prefer conda pinocchio over broken ROS humble py3.10 bindings.
sys.path[:] = [p for p in sys.path if p and "ros" not in p.lower()]

import pinocchio as pin  # noqa: E402
from scipy.optimize import least_squares  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
URDF = ROOT / "assets" / "wheeldog" / "urdf" / "wheeldog.urdf"
OUT = ROOT / "wheeldog_ext" / "stand_q0_pinocchio.yaml"

WHEEL_FRAMES = ["FL_W_L", "FR_W_L", "RL_W_L", "RR_W_L"]
WHEEL_RADIUS = 0.097
TARGET_BASE_Z = 0.505
H1_OUT = 0.02

# Joint order in URDF (actuated)
LEG_ORDER = [
    ("FL_H1_L_j1", "FL_H2_L_j2", "FL_K_L_j3"),
    ("FR_H1_L_j1", "FR_H2_L_j2", "FR_K_L_j3"),
    ("RL_H1_L_j1", "RL_H2_L_j2", "RL_K_L_j3"),
    ("RR_H1_L_j1", "RR_H2_L_j2", "RR_K_L_j3"),
]
# Sign pattern: L+ / R- for H2,K on left vs right front; rear mirrored
# Seed near existing dog-stance
SEED = {
    "FL_H1_L_j1": H1_OUT,
    "FL_H2_L_j2": 0.71,
    "FL_K_L_j3": 1.42,
    "FR_H1_L_j1": -H1_OUT,
    "FR_H2_L_j2": -0.71,
    "FR_K_L_j3": -1.42,
    "RL_H1_L_j1": -H1_OUT,
    "RL_H2_L_j2": -0.71,
    "RL_K_L_j3": -1.42,
    "RR_H1_L_j1": H1_OUT,
    "RR_H2_L_j2": 0.71,
    "RR_K_L_j3": 1.42,
}


def _joint_id(model: pin.Model, name: str) -> int:
    jid = model.getJointId(name)
    if jid >= model.njoints:
        raise KeyError(name)
    return jid


def main() -> None:
    if not URDF.is_file():
        raise FileNotFoundError(URDF)

    model = pin.buildModelFromUrdf(str(URDF))
    data = model.createData()
    print(f"[pin] nq={model.nq} nv={model.nv} njoints={model.njoints}")

    # Optimize only H2/K (8 vars); H1 fixed; wheels 0
    free_names = []
    for _, h2, k in LEG_ORDER:
        free_names.extend([h2, k])

    q0 = pin.neutral(model)
    name_to_qidx = {}
    for name in list(SEED) + [f"{p}_W_L_j4" for p in ("FL", "FR", "RL", "RR")]:
        jid = _joint_id(model, name)
        # revolute → q index = idx_q
        qidx = model.joints[jid].idx_q
        name_to_qidx[name] = qidx
        if name in SEED:
            q0[qidx] = SEED[name]

    frame_ids = [model.getFrameId(f) for f in WHEEL_FRAMES]
    for fid, fname in zip(frame_ids, WHEEL_FRAMES):
        if fid >= model.nframes:
            raise KeyError(f"frame {fname}")

    free_qidx = np.array([name_to_qidx[n] for n in free_names], dtype=int)
    x0 = q0[free_qidx].copy()

    # Target: wheel center z in world = WHEEL_RADIUS when base at TARGET_BASE_Z.
    # URDF has fixed base at identity; interpret FK in base frame, then z_world = z_base + TARGET_BASE_Z.
    z_target_in_base = WHEEL_RADIUS - TARGET_BASE_Z  # ≈ -0.408

    def residuals(x: np.ndarray) -> np.ndarray:
        q = q0.copy()
        q[free_qidx] = x
        pin.forwardKinematics(model, data, q)
        pin.updateFramePlacements(model, data)
        errs = []
        zs = []
        for fid in frame_ids:
            z = data.oMf[fid].translation[2]
            zs.append(z)
            errs.append(z - z_target_in_base)
        # Prefer knees ~ 2 * |thigh| (tuck), mild
        for i in range(0, 8, 2):
            h2, k = x[i], x[i + 1]
            errs.append(0.15 * (abs(k) - 2.0 * abs(h2)))
        # Keep left/right magnitude symmetry
        errs.append(0.2 * (abs(x[0]) - abs(x[2])))
        errs.append(0.2 * (abs(x[1]) - abs(x[3])))
        errs.append(0.2 * (abs(x[4]) - abs(x[6])))
        errs.append(0.2 * (abs(x[5]) - abs(x[7])))
        return np.asarray(errs, dtype=float)

    bounds_lo = np.full(8, -2.8)
    bounds_hi = np.full(8, 2.8)
    res = least_squares(residuals, x0, bounds=(bounds_lo, bounds_hi), xtol=1e-10)
    q = q0.copy()
    q[free_qidx] = res.x
    pin.forwardKinematics(model, data, q)
    pin.updateFramePlacements(model, data)

    stand = {n: float(SEED[n]) for n in SEED}
    for n, qi in zip(free_names, free_qidx):
        stand[n] = float(q[qi])
    for p in ("FL", "FR", "RL", "RR"):
        stand[f"{p}_W_L_j4"] = 0.0

    zs = [float(data.oMf[fid].translation[2] + TARGET_BASE_Z) for fid in frame_ids]
    print("[pin] wheel world-z (want ≈ r):", [f"{z:.4f}" for z in zs])
    print("[pin] cost", float(res.cost), "success", bool(res.success))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Auto-generated by optimize_stand_q0_pinocchio.py",
        f"target_base_z: {TARGET_BASE_Z}",
        f"wheel_radius: {WHEEL_RADIUS}",
        f"pinocchio_version: {pin.__version__}",
        "joint_pos:",
    ]
    for k, v in stand.items():
        lines.append(f"  {k}: {v:.6f}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"[pin] wrote {OUT}")
    print(json.dumps(stand, indent=2))


if __name__ == "__main__":
    main()
